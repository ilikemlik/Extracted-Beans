/* ==========================================================================
   EXTRACTED BEANS - VERCEL BUILD SCRIPT
   Generates `firebase-config.js` from Vercel Environment Variables at deploy time.
   This keeps credentials and passcodes safe from public Git repositories.
   ========================================================================== */

const fs = require('fs');
const path = require('path');

const targetPath = path.join(__dirname, 'firebase-config.js');
const templatePath = path.join(__dirname, 'firebase-config.example.js');

// 1. Single environment variable containing the entire file content
if (process.env.FIREBASE_CONFIG_JS && process.env.FIREBASE_CONFIG_JS.trim()) {
  fs.writeFileSync(targetPath, process.env.FIREBASE_CONFIG_JS.trim() + '\n', 'utf8');
  console.log('[build] Successfully generated firebase-config.js from FIREBASE_CONFIG_JS.');
  process.exit(0);
}

// 2. Individual environment variables configured in Vercel Dashboard
if (process.env.FIREBASE_API_KEY || process.env.FIREBASE_PROJECT_ID) {
  const apiKey = process.env.FIREBASE_API_KEY || '';
  const projectId = process.env.FIREBASE_PROJECT_ID || '';
  const authDomain = process.env.FIREBASE_AUTH_DOMAIN || (projectId ? `${projectId}.firebaseapp.com` : '');
  const storageBucket = process.env.FIREBASE_STORAGE_BUCKET || (projectId ? `${projectId}.firebasestorage.app` : '');
  const messagingSenderId = process.env.FIREBASE_MESSAGING_SENDER_ID || '';
  const appId = process.env.FIREBASE_APP_ID || '';
  const measurementId = process.env.FIREBASE_MEASUREMENT_ID || '';
  const adminPasscode = process.env.ADMIN_PASSCODE || '1234';

  const configContent = `/* ==========================================================================
   EXTRACTED BEANS - FIREBASE FIRESTORE CONFIGURATION
   Generated by Vercel Build Step
   ========================================================================== */

export const firebaseConfig = {
  apiKey: ${JSON.stringify(apiKey)},
  authDomain: ${JSON.stringify(authDomain)},
  projectId: ${JSON.stringify(projectId)},
  storageBucket: ${JSON.stringify(storageBucket)},
  messagingSenderId: ${JSON.stringify(messagingSenderId)},
  appId: ${JSON.stringify(appId)},
  measurementId: ${JSON.stringify(measurementId)}
};

export const ADMIN_PASSCODE = ${JSON.stringify(adminPasscode)};

export function isFirebaseConfigured() {
  return Boolean(
    firebaseConfig &&
    firebaseConfig.apiKey &&
    !firebaseConfig.apiKey.includes('YOUR_') &&
    firebaseConfig.projectId &&
    !firebaseConfig.projectId.includes('YOUR_')
  );
}
`;

  fs.writeFileSync(targetPath, configContent, 'utf8');
  console.log('[build] Successfully generated firebase-config.js from Vercel environment variables.');
  process.exit(0);
}

// 3. Fallback: if already exists, leave it; otherwise create from template
if (fs.existsSync(targetPath)) {
  console.log('[build] Using existing firebase-config.js.');
} else if (fs.existsSync(templatePath)) {
  fs.copyFileSync(templatePath, targetPath);
  console.log('[build] No environment variables set; copied firebase-config.example.js as fallback.');
}
